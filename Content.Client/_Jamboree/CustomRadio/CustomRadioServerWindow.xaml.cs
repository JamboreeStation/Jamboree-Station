using System.Linq;
using Content.Shared._Jamboree.CustomRadio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Jamboree.CustomRadio;

[GenerateTypedNameReferences]
public sealed partial class CustomRadioServerWindow : DefaultWindow
{
    public event Action<string, string, string, Color>? OnSave;

    private string? _editingId;

    public CustomRadioServerWindow()
    {
        RobustXamlLoader.Load(this);
        NameEdit.OnTextChanged += _ => UpdatePreview();
        ColorSelector.OnColorChanged += _ => UpdatePreview();

        SaveButton.OnPressed += _ =>
        {
            if (_editingId != null)
                OnSave?.Invoke(_editingId, NameEdit.Text, KeyEdit.Text, ColorSelector.Color);
        };
    }

    public void UpdateState(CustomRadioServerBoundUserInterfaceState state)
    {
        ChannelList.RemoveAllChildren();
        EmptyLabel.Visible = state.Channels.Count == 0;

        foreach (var channel in state.Channels)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            row.AddChild(new Label
            {
                Text = Loc.GetString("custom-radio-server-window-row", ("name", channel.Name), ("key", channel.Key), ("count", channel.Headsets)),
                FontColorOverride = channel.Color,
                HorizontalExpand = true,
            });

            var editButton = new Button { Text = Loc.GetString("custom-radio-server-window-edit")};

            editButton.OnPressed += _ => StartEditing(channel);
            row.AddChild(editButton);

            ChannelList.AddChild(row);
        }

        if (_editingId != null && state.Channels.All(c => c.Id != _editingId))
        {
            _editingId = null;
            EditPanel.Visible = false;
        }
    }

    private void StartEditing(CustomRadioChannelEntry channel)
    {
        _editingId = channel.Id;
        NameEdit.Text = channel.Name;
        KeyEdit.Text = channel.Key;
        ColorSelector.Color = channel.Color;
        UpdatePreview();
        EditPanel.Visible = true;
    }

    private void UpdatePreview()
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            name = Loc.GetString("custom-key-window-name");

        ColorPreview.Text = Loc.GetString("custom-key-window-preview", ("name", name));
        ColorPreview.FontColorOverride = ColorSelector.Color;
    }
}