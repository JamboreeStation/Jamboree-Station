using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Jamboree.CustomRadio;

[GenerateTypedNameReferences]
public sealed partial class CustomEncryptionKeyWindow : DefaultWindow
{
    public event Action<string, string, Color>? OnConfirm;

    public CustomEncryptionKeyWindow()
    {
        RobustXamlLoader.Load(this);

        NameEdit.OnTextChanged += _ => UpdatePreview();
        ColorSelector.OnColorChanged += _ => UpdatePreview();
        ConfirmButton.OnPressed += _ => OnConfirm?.Invoke(NameEdit.Text, KeyEdit.Text, ColorSelector.Color);
        UpdatePreview();
    }

    private void UpdatePreview()
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            name = Loc.GetString("custom-key-window-name");

        ColorPreview.Text = Loc.GetString("custom-key-window-preview", ("name", name));
        ColorPreview.FontColorOverride = ColorSelector.Color;
    }
}