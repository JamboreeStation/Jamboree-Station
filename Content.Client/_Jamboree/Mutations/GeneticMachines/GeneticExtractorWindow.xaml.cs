using Content.Shared._Jamboree.Mutations;
using Content.Shared._Jamboree.Mutations.GeneticMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Jamboree.Mutations.GeneticMachines;

[GenerateTypedNameReferences]
public sealed partial class GeneticExtractorWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    public event Action<string?>? OnIsolatedGeneSelected;
    public event Action<string>? OnGenepackNameChanged;

    private TimeSpan? _startedAt;
    private TimeSpan? _finishesAt;

    public GeneticExtractorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        IsolatedGeneOption.OnItemSelected += args =>
        {
            IsolatedGeneOption.SelectId(args.Id);
            var meta = IsolatedGeneOption.GetItemMetadata(args.Id);
            OnIsolatedGeneSelected?.Invoke(meta as string);
        };

        IsolateWarning.SetMessage(Loc.GetString("extractor-isolate-kill-warning"));

        GenepackNameInput.OnTextEntered += args => OnGenepackNameChanged?.Invoke(args.Text);
        GenepackNameInput.OnFocusExit += _ => OnGenepackNameChanged?.Invoke(GenepackNameInput.Text);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        GeneticMachineProgress.Update(_timing, ProgressBar, _startedAt, _finishesAt);
    }

    public void Populate(GeneticExtractorBoundUserInterfaceState state)
    {
        _startedAt = state.StartedAt;
        _finishesAt = state.FinishesAt;

        StatusLabel.SetMessage(state.Status switch
        {
            GeneticMachineScannerStatus.NoScannerLinked => Loc.GetString("genetic-machine-no-scanner"),
            GeneticMachineScannerStatus.ScannerOutOfRange => Loc.GetString("genetic-machine-scanner-far"),
            GeneticMachineScannerStatus.ScannerEmpty => Loc.GetString("genetic-machine-scanner-empty"),
            GeneticMachineScannerStatus.ScannerOccupied => Loc.GetString("genetic-machine-scanner-ready"),
            _ => string.Empty,
        });
        OccupantLabel.SetMessage(string.IsNullOrEmpty(state.OccupantName)
            ? string.Empty
            : Loc.GetString("genetic-machine-occupant", ("name", state.OccupantName)));

        CleanseModeButton.Pressed = state.Mode == GeneticExtractorMode.Cleanse;
        IsolateModeButton.Pressed = state.Mode == GeneticExtractorMode.Isolate;
        IsolatePanel.Visible = state.Mode == GeneticExtractorMode.Isolate;

        ModeBlurb.SetMessage(state.Mode == GeneticExtractorMode.Cleanse
            ? Loc.GetString("extractor-mode-cleanse-blurb")
            : Loc.GetString("extractor-mode-isolate-blurb"));

        IsolatedGeneOption.Clear();
        IsolatedGeneOption.AddItem(Loc.GetString("extractor-isolate-none"), 0);
        IsolatedGeneOption.SetItemMetadata(0, null!);
        var idx = 1;
        var selectedIdx = 0;
        foreach (var id in state.OccupantMutationIds)
        {
            var name = _proto.TryIndex<MutationPrototype>(id, out var proto) ? proto.Name : id;
            IsolatedGeneOption.AddItem(name, idx);
            IsolatedGeneOption.SetItemMetadata(idx, id);
            if (state.IsolatedMutationId == id)
                selectedIdx = idx;
            idx++;
        }
        IsolatedGeneOption.SelectId(selectedIdx);

        // Don't yank the text out from under the geneticist while they're typing.
        if (!GenepackNameInput.HasKeyboardFocus())
            GenepackNameInput.Text = state.GenepackName;

        ActivateButton.Disabled = state.Busy || state.Status != GeneticMachineScannerStatus.ScannerOccupied;
        BusyLabel.Visible = state.Busy;
    }
}
