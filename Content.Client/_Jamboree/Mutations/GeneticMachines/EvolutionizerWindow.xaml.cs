using Content.Shared._Jamboree.Mutations.GeneticMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Jamboree.Mutations.GeneticMachines;

[GenerateTypedNameReferences]
public sealed partial class EvolutionizerWindow : DefaultWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;

    private TimeSpan? _startedAt;
    private TimeSpan? _finishesAt;

    public EvolutionizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        GeneticMachineProgress.Update(_timing, ProgressBar, _startedAt, _finishesAt);
    }

    public void Populate(EvolutionizerBoundUserInterfaceState state)
    {
        _startedAt = state.StartedAt;
        _finishesAt = state.FinishesAt;
        StatusLabel.SetMessage(state.Status switch
        {
            GeneticMachineScannerStatus.NoScannerLinked => Loc.GetString("genetic-machine-no-scanner"),
            GeneticMachineScannerStatus.ScannerOutOfRange => Loc.GetString("genetic-machine-scanner-far"),
            GeneticMachineScannerStatus.ScannerEmpty => Loc.GetString("genetic-machine-scanner-empty"),
            GeneticMachineScannerStatus.ScannerOccupied => Loc.GetString("genetic-machine-scanner-ready"),
            _ => string.Empty,
        });
        OccupantLabel.SetMessage(string.IsNullOrEmpty(state.OccupantName)
            ? string.Empty
            : Loc.GetString("genetic-machine-occupant", ("name", state.OccupantName)));
        EmagPanel.Visible = state.Emagged;
        if (state.Emagged && !DnaInput.HasKeyboardFocus())
            DnaInput.Text = state.CurrentDnaFingerprint;
        CannotEvolveLabel.SetMessage(Loc.GetString("evolutionizer-cannot-evolve"));
        CannotEvolveLabel.Visible = state.OccupantCannotEvolve;
        DnaDonorMissingLabel.SetMessage(Loc.GetString("evolutionizer-dna-donor-missing"));
        DnaDonorMissingLabel.Visible = state.DnaDonorNotFound;
        ActivateButton.Disabled = state.Busy
            || state.Status != GeneticMachineScannerStatus.ScannerOccupied
            || state.OccupantCannotEvolve
            || state.DnaDonorNotFound;
        BusyLabel.Visible = state.Busy;
    }
}
