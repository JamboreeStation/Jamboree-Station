using System.Linq;
using Content.Shared._Jamboree.Mutations;
using Content.Shared._Jamboree.Mutations.GeneticMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Jamboree.Mutations.GeneticMachines;

[GenerateTypedNameReferences]
public sealed partial class RecombinerWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IEntityManager _ent = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    private readonly SpriteSystem _spriteSystem;

    public event Action<NetEntity>? OnPackToggleClicked;
    public event Action<NetEntity>? OnEjectClicked;

    private TimeSpan? _startedAt;
    private TimeSpan? _finishesAt;

    public RecombinerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _spriteSystem = _ent.System<SpriteSystem>();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        GeneticMachineProgress.Update(_timing, ProgressBar, _startedAt, _finishesAt);
    }

    public void Populate(RecombinerBoundUserInterfaceState state)
    {
        _startedAt = state.StartedAt;
        _finishesAt = state.FinishesAt;
        var selectedPackSet = state.SelectedPacks.ToHashSet();

        // Selected genes row (deduplicated union from all picked packs)
        SelectedGrid.RemoveAllChildren();
        foreach (var mutationId in state.UnionMutationIds)
        {
            if (!_proto.TryIndex<MutationPrototype>(mutationId, out var proto))
                continue;
            // These are read-only previews of the resulting injector. Clicking
            // them does nothing; selection is at the pack level.
            SelectedGrid.AddChild(MakeGeneIcon(proto));
        }

        // Library: one row per loaded pack with a toggle + eject
        LibraryContainer.RemoveAllChildren();
        foreach (var pack in state.LoadedGenepacks)
        {
            var isSelected = selectedPackSet.Contains(pack.Entity);
            var packEntity = pack.Entity;

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 6, 0, 2),
            };
            var toggle = new Button
            {
                Text = isSelected
                    ? Loc.GetString("recombiner-pack-toggle-on")
                    : Loc.GetString("recombiner-pack-toggle-off"),
                ToggleMode = true,
                Pressed = isSelected,
            };
            toggle.OnPressed += _ => OnPackToggleClicked?.Invoke(packEntity);
            header.AddChild(toggle);
            header.AddChild(new Label
            {
                Text = pack.Label,
                Margin = new Thickness(6, 0, 0, 0),
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
            });
            var ejectBtn = new Button
            {
                Text = Loc.GetString("recombiner-eject-genepack"),
                Margin = new Thickness(6, 0, 0, 0),
            };
            ejectBtn.OnPressed += _ => OnEjectClicked?.Invoke(packEntity);
            header.AddChild(ejectBtn);
            LibraryContainer.AddChild(header);

            // Show the genes inside the pack as a non-interactive preview.
            var grid = new GridContainer
            {
                Columns = 10,
                Margin = new Thickness(4, 0, 4, 4),
            };
            foreach (var mutationId in pack.MutationIds)
            {
                if (!_proto.TryIndex<MutationPrototype>(mutationId, out var proto))
                    continue;
                grid.AddChild(MakeGeneIcon(proto));
            }
            LibraryContainer.AddChild(grid);
        }

        // Stats
        ComplexityLabel.Text = $"{state.Complexity} / {state.ComplexityCap}";
        MetabolicLabel.Text = state.MetabolicEfficiency.ToString("+#;-#;0");
        BalanceLabel.Text = state.Balanced
            ? Loc.GetString("recombiner-balanced", ("plus", state.PositiveCount), ("minus", state.NegativeCount))
            : Loc.GetString("recombiner-unbalanced", ("plus", state.PositiveCount), ("minus", state.NegativeCount));
        if (!GenotypeInput.HasKeyboardFocus())
            GenotypeInput.Text = state.GenotypeName;
        StartButton.Disabled = state.Busy || !state.Balanced;
        BusyLabel.Visible = state.Busy;
    }

    /// <summary>
    ///     A non-interactive gene icon used in both the selected-row preview and
    ///     the per-pack library preview. The Recombiner no longer lets you click
    ///     individual genes — selection is whole-pack.
    /// </summary>
    private Control MakeGeneIcon(MutationPrototype proto)
    {
        var panel = new PanelContainer
        {
            MinSize = new System.Numerics.Vector2(56, 56),
            Margin = new Thickness(2),
            MouseFilter = Control.MouseFilterMode.Stop,
            ToolTip = $"{proto.Name}\n{proto.Description}\n" +
                Loc.GetString("recombiner-tooltip-stats",
                    ("complexity", proto.Complexity),
                    ("efficiency", proto.MetabolicEfficiency),
                    ("kind", proto.Beneficial ? "+" : "-")),
        };

        if (proto.Icon is { } icon)
        {
            panel.AddChild(new TextureRect
            {
                Texture = _spriteSystem.Frame0(icon),
                TextureScale = new System.Numerics.Vector2(1.5f, 1.5f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalAlignment = Control.HAlignment.Center,
                VerticalAlignment = Control.VAlignment.Center,
                // Pass mouse events through so the panel's tooltip still triggers.
                MouseFilter = Control.MouseFilterMode.Ignore,
            });
        }
        else
        {
            panel.AddChild(new Label
            {
                Text = proto.Name,
                ClipText = true,
                HorizontalAlignment = Control.HAlignment.Center,
                VerticalAlignment = Control.VAlignment.Center,
                MouseFilter = Control.MouseFilterMode.Ignore,
            });
        }
        return panel;
    }
}
