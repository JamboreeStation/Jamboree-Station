using System.Linq;
using System.Text;
using Content.Shared._Jamboree.Telecomms;
using Content.Shared.Radio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Jamboree.Telecomms;

[GenerateTypedNameReferences]
public sealed partial class NtslConsoleWindow : DefaultWindow
{
    private const int NoServerId = -1;
    private const string Indent = "    ";
    private const int MaxShownChoices = 8;

    [Dependency] private IPrototypeManager _prototype = default!;

    public event Action<NetEntity>? OnServerSelected;
    public event Action<string>? OnUpload;
    public event Action? OnClear;
    public event Action? OnRestore;
    public event Action<bool>? OnEnabledChanged;
    public event Action? OnRefresh;

    private readonly List<NetEntity> _servers = new();
    private NetEntity? _shownServer;
    private string _shownCode = string.Empty;
    private bool _tabHeld;

    private readonly NtslEditorHints _hints;
    private Rope.Node? _hintRope;
    private int _hintCursor = -1;

    public NtslConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _hints = new NtslEditorHints(_prototype.EnumeratePrototypes<RadioChannelPrototype>().Select(p => p.ID.ToLowerInvariant()));

        CodeEdit.Placeholder = new Rope.Leaf(Loc.GetString("ntsl-console-window-placeholder"));
        CodeEdit.OnKeyBindDown += OnCodeKeyDown;
        CodeEdit.OnKeyBindUp += OnCodeKeyUp;

        ServerSelector.OnItemSelected += args =>
        {
            ServerSelector.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _servers.Count)
                OnServerSelected?.Invoke(_servers[args.Id]);
        };

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        UploadButton.OnPressed += _ => OnUpload?.Invoke(Rope.Collapse(CodeEdit.TextRope));
        ClearButton.OnPressed += _ => OnClear?.Invoke();
        RestoreButton.OnPressed += _ => OnRestore?.Invoke();
        EnabledCheckBox.OnToggled += args => OnEnabledChanged?.Invoke(args.Pressed);
    }

    public void UpdateState(NtslConsoleBoundUserInterfaceState state)
    {
        _servers.Clear();
        ServerSelector.Clear();
        ServerSelector.AddItem(Loc.GetString("ntsl-console-window-choose-server"), NoServerId);
        for (var i = 0; i < state.Servers.Count; i++)
        {
            _servers.Add(state.Servers[i].Server);
            ServerSelector.AddItem(state.Servers[i].Label, i);
        }

        var selectedIndex = state.Selected is { } selected ? _servers.IndexOf(selected) : -1;
        ServerSelector.SelectId(selectedIndex >= 0 ? selectedIndex : NoServerId);

        NoServerLabel.Visible = selectedIndex < 0;
        ServerPanel.Visible = selectedIndex >= 0;

        if (state.Selected != _shownServer || state.Code != _shownCode)
        {
            CodeEdit.TextRope = new Rope.Leaf(state.Code);
            _shownServer = state.Selected;
            _shownCode = state.Code;
        }

        EnabledCheckBox.Pressed = state.Enabled;
        RestoreButton.Disabled = !state.HasPrevious;
        OutputLabel.SetMessage(FormattedMessage.FromUnformatted(state.Output ?? string.Empty));

        var log = state.Log.Count == 0
            ? Loc.GetString("ntsl-console-window-log-empty")
            : string.Join("\n", state.Log);
        LogLabel.SetMessage(FormattedMessage.FromUnformatted(log));
    }

    private static bool IsTab(BoundKeyFunction function)
    {
        return function == EngineKeyFunctions.TextTabComplete || function == EngineKeyFunctions.GuiTabNavigateNext;
    }

    // Tab and Enter behave like in a code editor
    private void OnCodeKeyDown(GUIBoundKeyEventArgs args)
    {
        if (IsTab(args.Function))
        {
            if (!_tabHeld)
                PressTab();

            _tabHeld = true;
            args.Handle();
            return;
        }

        _tabHeld = false;
        if (args.Function != EngineKeyFunctions.TextNewline)
            return;

        var text = Rope.Collapse(CodeEdit.TextRope);
        var cursor = Math.Clamp(CodeEdit.CursorPosition.Index, 0, text.Length);
        var lineStart = cursor == 0 ? 0 : text.LastIndexOf('\n', cursor - 1) + 1;
        var line = text[lineStart..cursor];

        var indent = line[..(line.Length - line.TrimStart(' ').Length)];
        if (line.TrimEnd().EndsWith('{'))
            indent += Indent;

        CodeEdit.InsertAtCursor("\n" + indent);
        args.Handle();
    }

    private void OnCodeKeyUp(GUIBoundKeyEventArgs args)
    {
        if (IsTab(args.Function))
            _tabHeld = false;
    }

    // Tab finishes the name being typed, and indents when there is nothing to finish.
    private void PressTab()
    {
        SyncHints();
        var completion = _hints.Complete(CodeEdit.CursorPosition.Index);
        if (completion == null)
            CodeEdit.InsertAtCursor(Indent);
        else if (completion.Length > 0)
            CodeEdit.InsertAtCursor(completion);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var cursor = CodeEdit.CursorPosition.Index;
        if (ReferenceEquals(CodeEdit.TextRope, _hintRope) && cursor == _hintCursor)
            return;

        SyncHints();
        _hintCursor = cursor;
        UpdateHint(cursor);
    }

    private void SyncHints()
    {
        if (ReferenceEquals(CodeEdit.TextRope, _hintRope))
            return;

        _hintRope = CodeEdit.TextRope;
        _hints.SetCode(Rope.Collapse(_hintRope));
    }

    private void UpdateHint(int cursor)
    {
        var markup = new StringBuilder("[color=gray]");
        var choices = _hints.Choices(cursor);

        if (choices.Count > 0)
        {
            var names = string.Join("  ", choices.Take(MaxShownChoices));
            if (choices.Count > MaxShownChoices)
                names += "  ...";

            markup.Append(Loc.GetString("ntsl-console-window-hint-choices", ("names", $"[font=\"Monospace\"]{names}[/font]")));
        }
        else if (_hints.TryGetCall(cursor, out var name, out var parameters, out var argument))
        {
            // Highlight the argument being typed. Past the end, "..." stands for all the extra ones.
            var current = argument < parameters.Length ? argument
                : parameters.Length > 0 && parameters[^1] == "..." ? parameters.Length - 1
                : -1;

            markup.Append("[font=\"Monospace\"]").Append(FormattedMessage.EscapeText(name)).Append('(');
            for (var i = 0; i < parameters.Length; i++)
            {
                if (i > 0)
                    markup.Append(", ");

                var parameter = FormattedMessage.EscapeText(parameters[i]);
                if (i == current)
                    markup.Append("[color=white][font=\"MonospaceBold\"]").Append(parameter).Append("[/font][/color]");
                else
                    markup.Append(parameter);
            }

            markup.Append(")[/font]");
        }
        else
        {
            markup.Append(Loc.GetString("ntsl-console-window-hint-tip"));
        }

        markup.Append("[/color]");
        HintLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(markup.ToString()));
    }
}
